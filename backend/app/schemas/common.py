"""Common request and response schemas adhering to RFC 7807 problem details."""

from datetime import UTC, datetime
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class HealthResponse(BaseModel):
    """Liveness probe response model."""

    model_config = ConfigDict(extra="forbid")

    status: str = Field(default="alive", description="Process liveness state")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="UTC timestamp of the probe",
    )
    version: str = Field(description="Application version")


class ReadinessResponse(BaseModel):
    """Readiness probe response model inspecting critical dependencies."""

    model_config = ConfigDict(extra="forbid")

    status: str = Field(description="Overall readiness state ('ready' | 'degraded')")
    database: str = Field(description="Database connectivity status ('connected' | 'disconnected')")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="UTC timestamp of the probe",
    )
    details: dict[str, Any] = Field(
        default_factory=dict, description="Diagnostic details for dependencies"
    )


class SystemInfoResponse(BaseModel):
    """Sanitized system metadata response model."""

    model_config = ConfigDict(extra="forbid")

    app_name: str = Field(description="Application name")
    version: str = Field(description="Semantic version")
    environment: str = Field(description="Current deployment environment")
    debug: bool = Field(description="Whether debug mode is active")
    api_prefix: str = Field(description="Root prefix for API endpoints")
    features: dict[str, bool] = Field(description="Active feature toggles")


class ProblemDetails(BaseModel):
    """RFC 7807 compliant Problem Details error schema."""

    model_config = ConfigDict(extra="allow")

    type: str = Field(
        default="about:blank",
        description="URI reference identifying the problem type",
    )
    title: str = Field(description="Short human-readable summary of the problem")
    status: int = Field(description="HTTP status code generated by the origin server")
    detail: str = Field(description="Human-readable explanation specific to this occurrence")
    instance: str | None = Field(
        default=None, description="URI reference identifying the specific occurrence"
    )
    code: str = Field(
        default="INTERNAL_ERROR",
        description="Internal machine-readable error code",
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="UTC timestamp when error occurred",
    )
    request_id: str | None = Field(
        default=None, description="Distributed tracing or correlation ID"
    )
    errors: list[dict[str, Any]] | None = Field(
        default=None, description="Detailed validation error list if applicable"
    )
